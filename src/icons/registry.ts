/** Every semantic icon name understood by the library. */
export type IconName = keyof typeof iconRegistry;

/** Icon overrides: replace any registry entry. */
export type IconOverrides = Partial<Record<IconName, IconComponent>>;

export const iconNames = Object.keys(iconRegistry) as IconName[];

export const isIconName = (value: unknown): value is IconName =>
  typeof value === "string" && Object.prototype.hasOwnProperty.call(iconRegistry, value);
